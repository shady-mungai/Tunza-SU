CREATE TABLE IF NOT EXISTS users2 (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  name VARCHAR(120) NOT NULL,
  email VARCHAR(255) NOT NULL,
  admission_number VARCHAR(50) NOT NULL,
  password VARCHAR(255) NULL,
  google_subject VARCHAR(255) NULL,
  totp_secret VARCHAR(255) NULL,
  phone_number VARCHAR(30) NULL,
  role ENUM('student', 'maintenance_staff', 'admin') NOT NULL DEFAULT 'student',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  PRIMARY KEY (id),
  UNIQUE KEY uq_users_email (email),
  UNIQUE KEY uq_users_admission_number (admission_number),
  UNIQUE KEY uq_users_google_subject (google_subject),
  KEY idx_users_role (role)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE IF NOT EXISTS reports2 (
  id BIGINT UNSIGNED NOT NULL AUTO_INCREMENT,
  user_id BIGINT UNSIGNED NOT NULL,
  title VARCHAR(160) NOT NULL,
  description TEXT NOT NULL,
  location VARCHAR(255) NOT NULL,
  category VARCHAR(80) NOT NULL,
  priority ENUM('low', 'medium', 'high', 'urgent') NOT NULL,
  status ENUM('pending', 'in_progress', 'resolved', 'rejected') NOT NULL DEFAULT 'pending',
  image_url VARCHAR(500) NULL,
  assigned_to BIGINT UNSIGNED NULL,
  estimated_cost DECIMAL(12, 2) NULL,
  actual_cost DECIMAL(12, 2) NULL,
  estimated_completion_date DATETIME NULL,
  actual_completion_date DATETIME NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  completed_at DATETIME NULL,
  PRIMARY KEY (id),
  KEY idx_reports_user_created (user_id, created_at),
  KEY idx_reports_assignee_status (assigned_to, status),
  KEY idx_reports_status_created (status, created_at),
  CONSTRAINT fk_reports_user FOREIGN KEY (user_id) REFERENCES users2(id) ON DELETE RESTRICT,
  CONSTRAINT fk_reports_assignee FOREIGN KEY (assigned_to) REFERENCES users2(id) ON DELETE SET NULL
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;
